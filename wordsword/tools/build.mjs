// Generates sw.js with a precache list of every runtime file and a content hash as cache version.
// Run after any change: node tools/build.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";
const root = new URL("..", import.meta.url).pathname;
const include = ["index.html", "manifest.webmanifest", "css", "src", "vendor", "icons"];
const files = [];
const walk = p => statSync(p).isDirectory() ? readdirSync(p).forEach(f => walk(join(p, f))) : files.push(p);
include.forEach(f => walk(join(root, f)));
const h = createHash("sha256"); files.sort().forEach(f => h.update(f).update(readFileSync(f)));
const version = h.digest("hex").slice(0, 12);
const list = ["./"].concat(files.map(f => "./" + relative(root, f)));
writeFileSync(join(root, "sw.js"), `// Generated by tools/build.mjs — do not edit by hand.
// Caches the app shell and ALL content for offline use. User data lives in IndexedDB and is never touched here.
const VERSION = "${version}";
const CACHE = "wordsword-" + VERSION;
const FILES = ${JSON.stringify(list, null, 0)};
self.addEventListener("install", e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener("activate", e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("wordsword-") && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", e => {
  const req = e.request; if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  // cache-first for the versioned shell (a new deploy ships a new sw.js → new cache); network fallback
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(r => { if (r.ok) { const cp = r.clone(); caches.open(CACHE).then(c => c.put(req, cp)); } return r; })
    .catch(() => req.mode === "navigate" ? caches.match("./index.html") : Response.error())));
});
`);
console.log("sw.js:", list.length, "files, version", version);
